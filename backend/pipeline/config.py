def canonical_line(raw: str) -> str | None:
    """노선명 표기를 표준 노선명으로. 서울교통공사 파일은 호선을 '1', '2' 숫자만으로 적는다."""
    key = raw.strip().replace(" ", "")
    if key.isdigit():
        key = f"{key}호선"
    return _ALIAS_INDEX.get(key)


